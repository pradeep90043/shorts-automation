import assert from "assert";
import { isGeneratedShortChannel } from "../src/my-video/generatedChannels";
import { insightEnabledFor } from "../src/my-video/insightClip";

assert.ok(isGeneratedShortChannel("storiyum", {}), "Storiyum is generated by default");
assert.ok(!isGeneratedShortChannel("codeorcap", {}));
assert.ok(!isGeneratedShortChannel("storiyum", { STORIYUM_GENERATED: "off" }), "switch back to reel-based Shorts");
assert.ok(isGeneratedShortChannel("prompt_gag", { GENERATED_SHORT_CHANNELS: "storiyum, prompt_gag" }));
// a generated Short has no extra how-it-works clip; the other channels keep theirs
assert.ok(!insightEnabledFor("storiyum", "v2", {}));
assert.ok(insightEnabledFor("codeorcap", "v2", {}));
console.log("✓ generated Short channels");
