import assert from "assert";
import { isGeneratedShortChannel, usesGeneratedShort } from "../src/my-video/generatedChannels";
import { insightEnabledFor } from "../src/my-video/insightClip";

assert.ok(isGeneratedShortChannel("storiyum", {}), "Storiyum is generated by default");
assert.ok(isGeneratedShortChannel("codeorcap", {}), "CodeOrCap is generated by default");
assert.ok(isGeneratedShortChannel("prompt_gag", {}), "Prompt Gag is generated by default");
assert.ok(!isGeneratedShortChannel("infoonspot", {}), "InfoOnSpot keeps the real reel with its original audio");
assert.ok(!isGeneratedShortChannel("infoonspot", { GENERATED_SHORT_CHANNELS: "infoonspot,storiyum" }), "InfoOnSpot is never generated by the channel switch");
assert.ok(!isGeneratedShortChannel("storiyum", { STORIYUM_GENERATED: "off" }), "switch back to reel-based Shorts");
assert.ok(isGeneratedShortChannel("prompt_gag", { GENERATED_SHORT_CHANNELS: "storiyum, prompt_gag" }));
assert.ok(!isGeneratedShortChannel("codeorcap", { GENERATED_SHORT_CHANNELS: "storiyum" }));
assert.ok(!isGeneratedShortChannel("codeorcap", { GENERATED_SHORT_CHANNELS: "off" }));
// a YouTube source is only material on every channel, as before
assert.ok(usesGeneratedShort("infoonspot", "https://www.youtube.com/shorts/abc", {}));
assert.ok(!usesGeneratedShort("infoonspot", "https://www.instagram.com/reel/abc/", {}));
// a generated Short has no extra how-it-works clip; a reel-based channel keeps its own
assert.ok(!insightEnabledFor("storiyum", "v2", {}));
assert.ok(!insightEnabledFor("codeorcap", "v2", {}));
assert.ok(insightEnabledFor("codeorcap", "v2", { GENERATED_SHORT_CHANNELS: "storiyum" }));
console.log("✓ generated Short channels");
